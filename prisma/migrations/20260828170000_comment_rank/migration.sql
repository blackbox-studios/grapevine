-- AlterTable
-- The thread's rank, one number per comment. Written only by `commentScore()` in
-- src/lib/rank.js; the default is for the backfill below and for nothing else.
ALTER TABLE "comment" ADD COLUMN     "score" DOUBLE PRECISION NOT NULL DEFAULT 0;

-- Backfill every existing comment.
--
-- This is the one place the formula is also written in SQL, and it is frozen here as
-- history rather than maintained: a migration cannot import from src/, and a backfill run
-- afterwards by the application would leave the thread sorted by id in between. If the
-- weights are ever re-tuned, do NOT edit this file — run `npm run comments:rescore`, which
-- recomputes every row through the JavaScript that is the actual source of truth.
--
-- The constants below are LIKE_DOUBLING_HOURS = 6, POST_AUTHOR_HOURS = 12 and
-- EPOCH_MS = 2026-01-01T00:00:00Z. `created_at` is TIMESTAMP(3) without time zone and is
-- stored in UTC, so extracting its epoch and the origin's the same way keeps them
-- comparable.
UPDATE "comment" c
SET "score" = round(
        (
            (extract(epoch FROM c."created_at") - extract(epoch FROM TIMESTAMP '2026-01-01 00:00:00')) / 3600
            + 6 * log(2, (c."like_count" + 1)::numeric)
            + CASE WHEN c."author_id" = p."author_id" THEN 12 ELSE 0 END
        )::numeric,
        6
    )::double precision
FROM "post" p
WHERE p."id" = c."post_id";

-- CreateIndex
-- Sort columns in the order the keyset cursor compares them, so one page of a thread is an
-- index range scan rather than a sort of every comment on the post.
CREATE INDEX "comment_post_id_score_id_idx" ON "comment"("post_id", "score" DESC, "id" DESC);
