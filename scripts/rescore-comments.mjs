/* Recompute `Comment.score` for every comment, through the same function the app writes it
 * with.
 *
 *   npm run comments:rescore          # rewrite every score that has changed
 *   npm run comments:rescore -- --dry # report what would change, write nothing
 *
 * ── Why this exists ─────────────────────────────────────────────────────────
 *
 * The thread's rank is a stored column (see src/lib/rank.js for why it has to be). A stored
 * ranking has exactly one maintenance problem: the weights that produced it are in code, and
 * changing them re-ranks nothing. Comments written before the change keep the score the old
 * constants gave them, comments written after get the new ones, and the thread is sorted by
 * which side of the deploy each comment landed on — which looks like the ranking is broken
 * rather than like it was re-tuned, and is impossible to reason about from the outside.
 *
 * So: `LIKE_DOUBLING_HOURS` and `POST_AUTHOR_HOURS` are tunable, and this is the second half
 * of tuning them. Change the constants, run this, and the whole corpus agrees again.
 *
 * Also the repair for anything that inserted a comment around the column — the migration's
 * backfill covers the rows that predate it, and this covers the rest.
 *
 * ── Safe against production, unlike the seeds ────────────────────────────────
 *
 * No `requireLocalDatabase` here, deliberately. This writes one derived column and derives it
 * from `created_at`, `like_count` and the post's author — all facts it only reads — so the
 * worst a wrong-database run does is recompute the value already there. It is also precisely
 * the thing you need to run against production after a re-tune. Everything it touches can be
 * regenerated by running it again.
 */

import "dotenv/config"

import { COMMENT_RANK, commentScore } from "../src/lib/rank.js"
import { describeDatabase } from "./db-target.mjs"
import { prisma } from "../prisma/seed-lib.js"

/* Rows per pass. Big enough that a full corpus is a handful of round trips, small enough
 * that the batched update stays one reasonable statement. */
const BATCH = 200

const dry = process.argv.slice(2).includes("--dry")

const main = async () => {
    console.log(`\n→ database: ${describeDatabase()}`)
    console.log(
        `  weights: ${COMMENT_RANK.LIKE_DOUBLING_HOURS}h per doubling of likes, ` +
            `${COMMENT_RANK.POST_AUTHOR_HOURS}h for the post author`,
    )
    if (dry) console.log("  --dry: nothing will be written")

    let cursor = null
    let seen = 0
    let changed = 0

    for (;;) {
        /* Keyset on `id` rather than on the score being rewritten — paging a table by the
         * column you are updating is how a row gets visited twice or skipped. */
        const rows = await prisma.comment.findMany({
            where: cursor ? { id: { gt: cursor } } : {},
            orderBy: { id: "asc" },
            take: BATCH,
            select: {
                id: true,
                createdAt: true,
                likeCount: true,
                authorId: true,
                score: true,
                post: { select: { authorId: true } },
            },
        })
        if (rows.length === 0) break

        cursor = rows[rows.length - 1].id
        seen += rows.length

        const updates = rows
            .map((comment) => ({
                id: comment.id,
                was: comment.score,
                score: commentScore({
                    createdAt: comment.createdAt,
                    likeCount: comment.likeCount,
                    byPostAuthor: comment.authorId === comment.post.authorId,
                }),
            }))
            .filter((update) => update.score !== update.was)

        changed += updates.length

        /* The array form, so a batch is one round trip rather than one per row. */
        if (!dry && updates.length > 0) {
            await prisma.$transaction(
                updates.map((update) =>
                    prisma.comment.update({
                        where: { id: update.id },
                        data: { score: update.score },
                        select: { id: true },
                    }),
                ),
            )
        }
    }

    const verb = dry ? "would change" : "rescored"
    console.log(`\n✓ ${seen} comment${seen === 1 ? "" : "s"} read, ${changed} ${verb}.\n`)
}

main()
    .catch((error) => {
        console.error(`\n✗ ${error.message}\n`)
        process.exitCode = 1
    })
    .finally(() => prisma.$disconnect())
